import { defineConfig, type Plugin } from "vite"
import react from "@vitejs/plugin-react"
import path from "node:path"
import fs from "node:fs"
import esbuild, { type BuildContext } from "esbuild"
import { debug_bridge_plugin } from "./cli/debug/plugin.ts"

function service_worker_plugin(): Plugin {
    let dev_ctx: BuildContext | null = null

    return {
        name: "service-worker-plugin",
        configureServer(server) {
            server.middlewares.use(async (req, res, next) => {
                if (req.method !== "GET" && req.method !== "HEAD") return next()
                const url = new URL(req.url || "", "http://localhost")
                if (url.pathname !== "/sw.js") return next()

                try {
                    if (!dev_ctx) {
                        dev_ctx = await esbuild.context({
                            entryPoints: [path.resolve(import.meta.dirname, "frontend/sw/main.worker.ts")],
                            bundle: true,
                            format: "esm",
                            target: "esnext",
                            tsconfig: path.resolve(import.meta.dirname, "frontend/tsconfig.json"),
                            write: false,
                            banner: {
                                js: "// Generated in-memory by Vite service_worker_plugin"
                            }
                        })
                    }
                    const build_result = await dev_ctx.rebuild()
                    const output = build_result.outputFiles?.[0]?.text || ""

                    res.writeHead(200, {
                        "Content-Type": "application/javascript; charset=utf-8",
                        "Cache-Control": "no-cache, no-store, must-revalidate",
                        "Service-Worker-Allowed": "/"
                    })
                    if (req.method === "HEAD") {
                        res.end()
                    } else {
                        res.end(output)
                    }
                } catch (err) {
                    console.error("[ServiceWorker Plugin] Build error in dev:", err)
                    res.writeHead(500, { "Content-Type": "text/plain; charset=utf-8" })
                    res.end(String(err))
                }
            })

            server.httpServer?.on("close", () => {
                dev_ctx?.dispose()
                dev_ctx = null
            })

            server.watcher.on("change", (file) => {
                if (file.includes("/frontend/sw/")) {
                    server.ws.send({ type: "full-reload" })
                }
            })
        },
        async closeBundle() {
            await esbuild.build({
                entryPoints: [path.resolve(import.meta.dirname, "frontend/sw/main.worker.ts")],
                bundle: true,
                format: "esm",
                target: "esnext",
                tsconfig: path.resolve(import.meta.dirname, "frontend/tsconfig.json"),
                outfile: path.resolve(import.meta.dirname, "dist/sw.js"),
                minify: true,
                banner: {
                    js: "// Generated by frontend/sw/main.worker.ts"
                }
            })
        }
    }
}

function dual_alias_plugin(): Plugin {
    const resolve_file = (base_dir: string, sub_path: string) => {
        const full = path.resolve(import.meta.dirname, base_dir, sub_path)
        const candidates = [
            full,
            full + ".ts",
            full + ".tsx",
            full + ".js",
            full + ".jsx",
            path.join(full, "index.ts"),
            path.join(full, "index.tsx")
        ]
        for (const c of candidates) {
            if (fs.existsSync(c) && !fs.statSync(c).isDirectory()) {
                return c
            }
        }
        return null
    }

    return {
        name: "dual-alias-plugin",
        enforce: "pre",
        resolveId(source, importer) {
            if (!source.startsWith("@/")) return null
            const sub = source.slice(2)
            if (importer && importer.includes("/core/")) {
                const in_core = resolve_file("core", sub)
                if (in_core) return in_core
            }
            const in_frontend = resolve_file("frontend", sub)
            if (in_frontend) return in_frontend
            const in_core = resolve_file("core", sub)
            if (in_core) return in_core
            return null
        }
    }
}

function inject_core_plugin(): Plugin {
    const virtual_id = "virtual:inject-core"
    const resolved_virtual_id = `\0${virtual_id}`
    let dev_ctx: BuildContext | null = null
    let is_dev = false

    const build_options = (minify: boolean) => ({
        entryPoints: [path.resolve(import.meta.dirname, "frontend/inject/core/index.ts")],
        bundle: true,
        format: "iife" as const,
        target: "esnext",
        tsconfig: path.resolve(import.meta.dirname, "frontend/tsconfig.json"),
        write: false,
        minify
    })

    return {
        name: "inject-core-plugin",
        configResolved(config) {
            is_dev = config.command === "serve"
        },
        resolveId(id) {
            if (id === virtual_id) {
                return resolved_virtual_id
            }
            return null
        },
        async load(id) {
            if (id !== resolved_virtual_id) return null

            let output = ""
            if (is_dev) {
                if (!dev_ctx) {
                    dev_ctx = await esbuild.context(build_options(false))
                }
                const build_result = await dev_ctx.rebuild()
                output = build_result.outputFiles?.[0]?.text || ""
            } else {
                const build_result = await esbuild.build(build_options(true))
                output = build_result.outputFiles?.[0]?.text || ""
            }

            return `export default ${JSON.stringify(output)}`
        },
        configureServer(server) {
            server.httpServer?.on("close", () => {
                dev_ctx?.dispose()
                dev_ctx = null
            })

            server.watcher.on("change", (file) => {
                const normalized = file.replace(/\\/g, "/")
                if (normalized.includes("/frontend/inject/")) {
                    const mod = server.moduleGraph.getModuleById(resolved_virtual_id)
                    if (mod) {
                        server.moduleGraph.invalidateModule(mod)
                    }
                    server.ws.send({ type: "full-reload" })
                }
            })
        }
    }
}

